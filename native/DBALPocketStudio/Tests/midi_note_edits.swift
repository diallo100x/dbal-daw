import Foundation
let note=MIDIEvent(beat:2,duration:1,note:60,velocity:85)
let moved=MIDINoteEdits.moved(note,beats:0.37,pitches:7,grid:0.25)
precondition(moved.beat==2.25 && moved.note==67 && moved.duration==1 && moved.velocity==85 && moved.id==note.id)
precondition(note.beat==2 && note.note==60)
precondition(MIDINoteEdits.moved(note,beats:-8,pitches:-100,grid:0.25).beat==0)
precondition(MIDINoteEdits.moved(note,beats:0,pitches:1000,grid:nil).note==127)
precondition(MIDINoteEdits.resized(note,beats:-5,grid:0.25).duration==0.25)
precondition(abs(MIDINoteEdits.moved(note,beats:0.37,pitches:0,grid:nil).beat-2.37)<1e-9)
precondition(MIDINoteEdits.snapped(.nan,grid:0.25)==0)
precondition(MIDINoteEdits.resized(note,beats:-5,grid:.nan).duration==0.03125)
print("PASS: note movement, pitch bounds, snap/off, resize minimum, identity and velocity preservation.")
let loose=MIDIEvent(beat:2.37,duration:0.38,note:67,velocity:73)
let starts=MIDINoteEdits.quantized(loose,grid:0.25,mode:.starts)
precondition(starts.beat==2.25 && starts.duration==loose.duration)
precondition(starts.id==loose.id && starts.note==67 && starts.velocity==73)
let lengths=MIDINoteEdits.quantized(loose,grid:0.25,mode:.lengths)
precondition(lengths.beat==loose.beat && lengths.duration==0.5)
let both=MIDINoteEdits.quantized(loose,grid:0.25,mode:.both)
precondition(both.beat==2.25 && both.duration==0.5)
precondition(MIDINoteEdits.quantized(loose,grid:.nan,mode:.both)==loose)
precondition(MIDINoteEdits.quantized(loose,grid:0,mode:.both)==loose)
let tiny=MIDIEvent(beat:0.03,duration:0.01,note:60)
precondition(MIDINoteEdits.quantized(tiny,grid:0.25,mode:.both).duration==0.25)
let raw=MIDINoteEdits.recorded(start:2.37,end:2.75,note:67,velocity:73,grid:nil)
let input=MIDINoteEdits.recorded(start:2.37,end:2.75,note:67,velocity:73,grid:0.25)
precondition(raw.beat==2.37 && input.beat==2.25)
precondition(abs(raw.duration-input.duration)<1e-9 && abs(input.duration-0.38)<1e-9)
precondition(input.note==67 && input.velocity==73)
precondition(MIDINoteEdits.recorded(start:1,end:1,note:60,grid:0.25).duration==0.03125)
print("PASS: start/length/both quantize, invalid grids, identity/velocity preservation, independent input quantize and recorded gate length.")
